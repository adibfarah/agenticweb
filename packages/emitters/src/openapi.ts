import { fieldsToJsonSchema, type SiteGraph } from "@agenticweb-dev/core";

/** OpenAPI 3.1 description of the agent branch's REST interface. */
export function buildOpenApi(g: SiteGraph, opts: { baseUrl?: string; runtime?: boolean } = {}): Record<string, unknown> {
  const paths: Record<string, unknown> = {};
  const errorResponses = {
    "400": { description: "Invalid input. `errors` lists what to fix.", content: { "application/json": { schema: { $ref: "#/components/schemas/Error" } } } },
    "429": { description: "Rate limit reached. Retry after the `retry-after` header." },
  };

  if (opts.runtime) {
    paths["/ask"] = {
      post: {
        operationId: "ask",
        summary: "Ask a question about this site in plain language. Answers cite their sources.",
        requestBody: {
          required: true,
          content: { "application/json": { schema: { type: "object", required: ["query"], properties: { query: { type: "string" }, max_results: { type: "integer", minimum: 1, maximum: 20 } } } } },
        },
        responses: { "200": { description: "Answer with sources.", content: { "application/json": { schema: { $ref: "#/components/schemas/AskResponse" } } } }, ...errorResponses },
      },
    };
    paths["/api/search"] = {
      get: {
        operationId: "search",
        summary: "Search pages and entities.",
        parameters: [
          { name: "q", in: "query", required: true, schema: { type: "string" } },
          { name: "type", in: "query", required: false, schema: { type: "string" }, description: "Limit to a schema.org type" },
          { name: "limit", in: "query", required: false, schema: { type: "integer", default: 10 } },
        ],
        responses: { "200": { description: "Search results." } },
      },
    };
    paths["/api/actions/{id}"] = {
      get: {
        operationId: "get_action_status",
        summary: "Check the status of an action you started (for example, whether the guest confirmed).",
        parameters: [{ name: "id", in: "path", required: true, schema: { type: "string" } }],
        responses: { "200": { description: "Action status.", content: { "application/json": { schema: { $ref: "#/components/schemas/ActionResult" } } } } },
      },
    };
  }

  for (const a of g.actions) {
    paths[`/api/${a.name}`] = {
      post: {
        operationId: a.name,
        summary: a.description,
        "x-agent-kind": a.kind,
        "x-agent-confirmation": a.confirmation,
        ...(a.idempotency ? { "x-agent-idempotency": a.idempotency } : {}),
        parameters: a.kind === "read" ? [] : [{ name: "Idempotency-Key", in: "header", required: a.idempotency === "required", schema: { type: "string" }, description: "A unique key per attempt so retries never double-book or double-order." }],
        requestBody: { required: true, content: { "application/json": { schema: fieldsToJsonSchema(a.input) } } },
        responses: {
          "200": { description: "Done.", content: { "application/json": { schema: { $ref: "#/components/schemas/ActionResult" } } } },
          "202": { description: "Accepted; waiting for confirmation.", content: { "application/json": { schema: { $ref: "#/components/schemas/ActionResult" } } } },
          ...errorResponses,
        },
      },
    };
  }

  return {
    openapi: "3.1.0",
    info: { title: `${g.site.name}: agent API`, version: g.generatedAt.slice(0, 10), description: `Agent interface for ${g.site.url}. Generated by AgenticWeb.` },
    ...(opts.baseUrl ? { servers: [{ url: opts.baseUrl }] } : {}),
    paths,
    components: {
      schemas: {
        Error: { type: "object", properties: { error: { type: "string" }, errors: { type: "array", items: { type: "string" } } } },
        ActionResult: {
          type: "object",
          required: ["status"],
          properties: {
            id: { type: "string" },
            status: { enum: ["done", "pending_confirmation", "pending_owner", "checkout_link", "rejected", "failed", "expired"] },
            final: { type: "boolean", description: "True when nothing else will happen." },
            message: { type: "string" },
            checkout_url: { type: "string" },
            expires_at: { type: "string", format: "date-time" },
            data: { type: "object" },
          },
        },
        AskResponse: {
          type: "object",
          properties: {
            answer: { type: "string" },
            results: { type: "array", items: { type: "object" } },
            sources: { type: "array", items: { type: "string" } },
            updated: { type: "string" },
          },
        },
      },
    },
  };
}
